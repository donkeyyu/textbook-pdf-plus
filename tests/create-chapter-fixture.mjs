import { PDFDocument, PDFName, PDFString, StandardFonts } from '@cantoo/pdf-lib';
import { writeFileSync } from 'node:fs';
const target = process.argv[2];
if (!target) throw Error('Pass an output PDF path');
const pdf = await PDFDocument.create();
const font = await pdf.embedFont(StandardFonts.Helvetica);
const page = pdf.addPage([600, 800]);
page.drawText('Chapter 1 - Index workflow test', { x: 45, y: 750, size: 22, font });
page.drawText('Section 1 - First region', { x: 45, y: 670, size: 18, font });
page.drawText('Draw a rectangle around this line.', { x: 45, y: 610, size: 16, font });
page.drawText('Rename Section 1; its ID must stay the same.', { x: 45, y: 570, size: 14, font });
page.drawText('Section 2 - Second region', { x: 45, y: 370, size: 18, font });
page.drawText('Move the rectangle here to change its automatic association.', { x: 45, y: 310, size: 14, font });
page.drawText('A rectangle crossing y=400 must be marked ambiguous.', { x: 45, y: 270, size: 14, font });
const page2 = pdf.addPage([600, 800]);
page2.drawText('Chapter 2 - Final region', { x: 45, y: 750, size: 22, font });
page2.drawText('End of the isolated workflow fixture.', { x: 45, y: 650, size: 16, font });
const c = pdf.context;
const root = c.obj({ Type: 'Outlines' }); const rootRef = c.register(root);
const dest = (p, y) => c.obj([p.ref, PDFName.of('XYZ'), 0, y, 0]);
const ch1 = c.obj({ Title: PDFString.of('Chapter 1'), Parent: rootRef, Dest: dest(page, 800) }); const ch1Ref = c.register(ch1);
const ch2 = c.obj({ Title: PDFString.of('Chapter 2'), Parent: rootRef, Dest: dest(page2, 800) }); const ch2Ref = c.register(ch2);
const s1 = c.obj({ Title: PDFString.of('Section 1'), Parent: ch1Ref, Dest: dest(page, 700) }); const s1Ref = c.register(s1);
const s2 = c.obj({ Title: PDFString.of('Section 2'), Parent: ch1Ref, Dest: dest(page, 400) }); const s2Ref = c.register(s2);
root.set(PDFName.of('First'), ch1Ref); root.set(PDFName.of('Last'), ch2Ref); root.set(PDFName.of('Count'), c.obj(4));
ch1.set(PDFName.of('Next'), ch2Ref); ch2.set(PDFName.of('Prev'), ch1Ref);
ch1.set(PDFName.of('First'), s1Ref); ch1.set(PDFName.of('Last'), s2Ref); ch1.set(PDFName.of('Count'), c.obj(2));
s1.set(PDFName.of('Next'), s2Ref); s2.set(PDFName.of('Prev'), s1Ref);
pdf.catalog.set(PDFName.of('Outlines'), rootRef);
writeFileSync(target, await pdf.save());
console.log('Created isolated chapter fixture');
